"""Joint trajectory for the firmware PLAY command (slow open-loop preview of the walking gait, 2026-11-23).

Takes the simulated joint positions of one env of golden_rollout.bin (record_golden.py: flat_v1, stand 1 s, walk 4 s at
vx 0.1, freq 1.6, student v2ft) and writes playback.h into the same export folder. The firmware build picks it up
when present (EXPORT_DIR is on the include path).

  .venv_fw\\Scripts\\python.exe deploy\\export\\make_playback.py [export_dir] [--env 0]

Row layout of golden_rollout.bin (see deploy/firmware/test/test_host.c): 11 + 3J + obs_dim + J floats per env and
step; joint positions (absolute, firmware joint order) at [11, 11 + J).
"""
from __future__ import annotations

import argparse
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("export_dir", nargs="?", type=Path)
    ap.add_argument("--env", type=int, default=0)
    ap.add_argument("--skip-s", type=float, default=1.0, help="standing part at the start to drop")
    a = ap.parse_args()
    exp = a.export_dir or sorted((ROOT / "outputs" / "robot_v2" / "deploy").glob("export_*"))[-1]
    raw = (exp / "golden_rollout.bin").read_bytes()
    steps, envs, J, od = struct.unpack("<4i", raw[:16])
    row = 11 + 3 * J + od + J
    vals = struct.unpack(f"<{steps * envs * row}f", raw[16:16 + 4 * steps * envs * row])
    first = int(round(a.skip_s * 50))
    frames = []
    for t in range(first, steps):
        base = (t * envs + a.env) * row
        frames.append(vals[base + 11: base + 11 + J])
    lines = [
        "/* Generated by deploy/export/make_playback.py: simulated joint positions [rad] at 50 Hz, firmware joint order.",
        f" * Source: {exp.name}/golden_rollout.bin env {a.env}, steps {first}..{steps - 1} (walking part, flat_v1,",
        " * vx 0.1 m/s, 1.6 Hz). Used by the PLAY command (open loop, slowed down). */",
        "#pragma once",
        f"#define PLAYBACK_FRAMES {len(frames)}",
        f"static const float PLAYBACK[PLAYBACK_FRAMES][{J}] = {{",
    ]
    lines += ["    {" + ", ".join(f"{v:.5f}f" for v in fr) + "}," for fr in frames]
    lines += ["};", ""]
    (exp / "playback.h").write_text("\n".join(lines), encoding="ascii")
    import math
    span = [max(fr[j] for fr in frames) - min(fr[j] for fr in frames) for j in range(J)]
    print(f"[playback] {exp / 'playback.h'}: {len(frames)} frames ({len(frames) / 50:.2f} s)")
    print("  joint range [deg]: " + " ".join(f"{math.degrees(s):.0f}" for s in span))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
