"""Write the URDF of a model version from params.yaml + reports/mass_properties.json.

Run after build_parts.py (any Python with PyYAML; the CAD environment has it):
    .venv_cad\\Scripts\\python.exe hardware\\model\\generator\\build_urdf.py --version 1

Output: robot_v<N>/urdf/custom_biped_v<N>.urdf  (generated file, do not edit by hand)
- Visuals: the per-link STL meshes from build_parts.py (mm -> scale 0.001).
- Collisions: boxes / cylinders only (numbers below are in the zero-pose world frame, mm).
- Inertials: from the CAD mass properties (printed parts x effective density + servos + bought parts).
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from xml.dom import minidom
from xml.etree import ElementTree as ET

sys.path.insert(0, str(Path(__file__).resolve().parent))
import params as P  # noqa: E402

MM = 1e-3


def f(v, nd=6):
    return " ".join(f"{x:.{nd}g}" if abs(x) > 1e-12 else "0" for x in v)


def collisions(lay: P.Layout) -> dict[str, list[tuple]]:
    """Primitive collision shapes per link, as world zero-pose extents (mm):
    ("box", (x0, x1, y0, y1, z0, z1)) or ("cyl_x", (x0, x1, y, z, r))."""
    p = lay.p
    t = p["torso"]
    zr = lay.hip_roll_z
    fp = p["legs"]["foot"]
    y = p["legs"]["hip_spacing"] / 2
    T = lay.joint("tail_yaw").origin
    Q = lay.joint("tail_pitch").origin
    z_hp = lay.joint("left_hip_pitch").origin[2]
    z_kn = lay.joint("left_knee").origin[2]
    z_an = lay.joint("left_ankle_pitch").origin[2]
    tip = p["tail"]["tip"]
    xc = Q[0] - p["tail"]["length"]
    out = {
        "base": [("box", (*t["x"], *t["y"], zr + t["z_rel"][0], zr + t["z_rel"][1])),
                 ("box", (T[0] - 9.5, t["x"][0], -18, 18, T[2] - 15.5, T[2] + 15.5))],
        "tail_yaw_link": [("box", (Q[0] + 18, T[0] + 10.5, -14, 14, T[2] - 17.25, T[2] + 17.25))],
        "tail_pitch_link": [("box", (Q[0] - 34, Q[0] + 10.5, -17.25, 17.25, Q[2] - 11, Q[2] + 11)),
                            ("cyl_x", (xc + tip["length"] / 2, Q[0] - 34, 0, Q[2], p["tail"]["rod"]["diameter"] / 2)),
                            ("cyl_x", (xc - tip["length"] / 2, xc + tip["length"] / 2, 0, Q[2], tip["diameter"] / 2))],
    }
    for side, s in P.SIDES.items():
        ys = s * y
        out[f"{side}_hip"] = [("box", (-17.25, 17.25, ys - 17.25, ys + 17.25, z_hp + 10.5, zr - 10.5))]   # cross block core
        out[f"{side}_thigh"] = [("box", (-11, 11, ys - 17.25, ys + 17.25, z_kn + 5, z_hp))]
        out[f"{side}_shin"] = [("box", (-11, 11, ys - 17.25, ys + 17.25, z_an + 5, z_kn))]
        out[f"{side}_foot"] = [("box", (-fp["length"] / 2, fp["length"] / 2, ys - fp["width"] / 2, ys + fp["width"] / 2,
                                        0.0, fp["pad_thick"] - 0.5 + fp["plate"]))]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", type=int, required=True)
    args = ap.parse_args()
    vdir = P.version_dir(args.version)
    if (vdir / "FROZEN").exists():
        sys.exit(f"{vdir} is frozen (tagged). Create a new version instead of rebuilding it.")
    lay = P.load(args.version)
    mp = json.loads((vdir / "reports/mass_properties.json").read_text(encoding="utf-8"))
    act = lay.p["actuator"]
    jt = lay.p["joints"]
    origin = lay.link_origin
    name = f"{lay.p['robot']['name']}_v{args.version}"

    robot = ET.Element("robot", name=name)
    robot.append(ET.Comment(f" generated by generator/build_urdf.py from v{args.version}/params.yaml, "
                            f"git {mp['git_commit']}; do not edit by hand "))
    cols = collisions(lay)
    for link in ["base"] + [j.child for j in lay.joints]:
        o = origin[link]
        el = ET.SubElement(robot, "link", name=link)
        lp = mp["links"][link]
        ine = ET.SubElement(el, "inertial")
        ET.SubElement(ine, "origin", xyz=f([c * MM for c in lp["com_mm"]]), rpy="0 0 0")
        ET.SubElement(ine, "mass", value=f"{lp['mass_g'] / 1000:.6g}")
        I = lp["inertia_gmm2"]
        k = 1e-9
        ET.SubElement(ine, "inertia", ixx=f"{I[0][0] * k:.6g}", ixy=f"{I[0][1] * k:.6g}", ixz=f"{I[0][2] * k:.6g}",
                      iyy=f"{I[1][1] * k:.6g}", iyz=f"{I[1][2] * k:.6g}", izz=f"{I[2][2] * k:.6g}")
        vis = ET.SubElement(el, "visual")
        ET.SubElement(vis, "origin", xyz="0 0 0", rpy="0 0 0")
        g = ET.SubElement(vis, "geometry")
        ET.SubElement(g, "mesh", filename=f"../meshes/{link}.stl", scale="0.001 0.001 0.001")
        for kind, e in cols[link]:
            c = ET.SubElement(el, "collision")
            if kind == "box":
                x0, x1, y0, y1, z0, z1 = e
                ctr = ((x0 + x1) / 2 - o[0], (y0 + y1) / 2 - o[1], (z0 + z1) / 2 - o[2])
                ET.SubElement(c, "origin", xyz=f([v * MM for v in ctr]), rpy="0 0 0")
                ET.SubElement(ET.SubElement(c, "geometry"), "box", size=f([(x1 - x0) * MM, (y1 - y0) * MM, (z1 - z0) * MM]))
            else:
                x0, x1, yc, zc, r = e
                ctr = ((x0 + x1) / 2 - o[0], yc - o[1], zc - o[2])
                ET.SubElement(c, "origin", xyz=f([v * MM for v in ctr]), rpy=f"0 {math.pi / 2:.6f} 0")
                ET.SubElement(ET.SubElement(c, "geometry"), "cylinder", radius=f"{r * MM:.6g}", length=f"{abs(x1 - x0) * MM:.6g}")
    for j in lay.joints:
        po, co = origin[j.parent], origin[j.child]
        el = ET.SubElement(robot, "joint", name=j.name, type="revolute")
        ET.SubElement(el, "origin", xyz=f([(a - b) * MM for a, b in zip(co, po)]), rpy="0 0 0")
        ET.SubElement(el, "parent", link=j.parent)
        ET.SubElement(el, "child", link=j.child)
        ET.SubElement(el, "axis", xyz=f(j.axis))
        ET.SubElement(el, "limit", lower=f"{math.radians(j.lower):.6f}", upper=f"{math.radians(j.upper):.6f}",
                      effort=f"{act['saturation_effort']}", velocity=f"{act['velocity_limit']}")
        ET.SubElement(el, "dynamics", damping="0", friction=f"{jt['friction']}")
    xml = minidom.parseString(ET.tostring(robot, encoding="unicode")).toprettyxml(indent="  ")
    out = vdir / "urdf" / f"{name}.urdf"
    out.parent.mkdir(exist_ok=True)
    out.write_text(xml, encoding="utf-8")
    print(f"wrote {out}  (total mass {mp['total_mass_g']:.1f} g)")


if __name__ == "__main__":
    main()
